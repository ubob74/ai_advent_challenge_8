import GigaChat from 'gigachat';

const giga = new GigaChat({
    credentials: process.env.GIGACHAT_API_KEY,
    scope: 'GIGACHAT_API_PERS',
});

giga.chat({
    messages: [
    {
        role: 'user',
        content: `
            Написать программу на языке C, которая:
            - запрашивает у пользователя радиус круга;
            - вычисляет площадь круга по формуле S = π * r², где π ≈ 3.14159;
            - выводит результат вычисления площади с точностью до двух знаков после запятой.

            Программа должна:
            - использовать стандартные библиотеки языка C;
            - предусматривать ввод действительного (с плавающей точкой) числа;
            - обрабатывать возможные ошибки ввода (например, ввод нечисловых символов).

            Пример вывода программы:
            Введите радиус круга: 5.0
            Площадь круга с радиусом 5.00 составляет 78.54 квадратных единиц.`
    }
    ],
    "stream": false,
    "max_tokens": 512,
    "repetition_penalty": 1,
    "update_interval": 0
})

.then((resp) => {
    console.log(resp.choices[0]?.message.content);
});

